export type Key = keyof (typeof strings)['en'];

export function t(lang: Lang, key: Key, vars: Record<string, string | number> = {}): string {
  return strings[lang][key].replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}

const ruItems = new Intl.PluralRules('ru');
const ruWord = { one: 'позиция', few: 'позиции', many: 'позиций', other: 'позиции' } as const;

export function itemCount(lang: Lang, n: number): string {
  if (lang === 'ru') return `${n} ${ruWord[ruItems.select(n) as keyof typeof ruWord] ?? ruWord.other}`;
  if (lang === 'en' && n === 1) return '1 item';
  return t(lang, 'items', { n });
}

// Whole lari stay whole (₾ 20); anything with tetri shows two decimals (₾ 1.70).
export function price(n: number): string {
  const v = Math.round(n * 100) / 100;
  return `₾ ${Number.isInteger(v) ? v : v.toFixed(2)}`;
}
